#!/usr/bin/env python3
"""
Export per-day NQ price paths for the web simulator's real-data mode (docs/nq_days.js).

For every eligible day (same filters as PropTest.py: a 10:00 ET bar and a full session)
it stores, relative to the 10:00 open:
  * up[k-1] = first 1-min bar index (0 = 10:00) where High - entry >= k points
  * dn[k-1] = first 1-min bar index where entry - Low >= k points
  for k = 1..MAX_PTS, cut off at the day's maximum excursion, plus the last close
  before 16:00 for time exits. That is enough to replay any TP/SL bracket in whole points.

Arrays are non-decreasing, so they are delta-encoded to keep the file small.

USAGE
  python export_days.py NQ_1Min.csv
  python export_days.py NQ_1Min.csv --start 2021-08-09 --out docs/nq_days.js
"""
import argparse
import json
import numpy as np
from PropTest import load_csv, ENTRY_MINUTE, EXIT_MINUTE, MIN_LAST_BAR

MAX_PTS = 200    # largest stop/target the page can ask for (50 pt stop * 4R)


def first_hits(excursion: np.ndarray) -> list:
    k_max = min(MAX_PTS, int(np.floor(excursion[-1])))
    idx = np.searchsorted(excursion, np.arange(1, k_max + 1), side="left")
    return np.diff(idx, prepend=0).tolist()        # delta-encoded


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("csv")
    ap.add_argument("--start", default="2021-08-09", help="first date to include")
    ap.add_argument("--end", help="last date to include")
    ap.add_argument("--out", default="docs/nq_days.js")
    a = ap.parse_args()

    df = load_csv(a.csv)
    df = df[df["date"] >= a.start]
    if a.end:
        df = df[df["date"] <= a.end]

    # keep only the most-liquid contract per day (handles rollovers)
    if "Symbol" in df.columns and df["Symbol"].nunique() > 1:
        vol = df.groupby(["date", "Symbol"])["Volume"].sum().reset_index()
        best = vol.loc[vol.groupby("date")["Volume"].idxmax(), ["date", "Symbol"]]
        df = df.merge(best, on=["date", "Symbol"])

    days, skipped = [], 0
    first_date = last_date = None
    for date, g in df.groupby("date"):
        g = g[(g["minute"] >= ENTRY_MINUTE) & (g["minute"] < EXIT_MINUTE)]
        if g.empty or g["minute"].iloc[0] != ENTRY_MINUTE or g["minute"].iloc[-1] < MIN_LAST_BAR:
            skipped += 1
            continue
        entry = g["Open"].iloc[0]
        up = np.maximum.accumulate(g["High"].to_numpy() - entry)
        dn = np.maximum.accumulate(entry - g["Low"].to_numpy())
        first_date = first_date or date
        last_date = date
        days.append([(date - first_date).days,                      # calendar-day offset
                     round(float(g["Close"].iloc[-1] - entry), 2),  # time-exit P&L in points (long)
                     first_hits(up), first_hits(dn)])

    if not days:
        raise SystemExit("No eligible days in the selected range.")
    data = {"symbol": "NQ", "first": str(first_date.date()), "last": str(last_date.date()),
            "entry": "10:00 ET", "exit": "16:00 ET", "maxPts": MAX_PTS, "days": days}
    with open(a.out, "w", encoding="utf-8") as f:
        f.write("// Generated by export_days.py - per-day NQ excursion paths for the simulator\n")
        f.write("window.NQ_DAYS = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(f"Wrote {len(days)} days ({first_date.date()} -> {last_date.date()}), skipped {skipped}, to {a.out}")


if __name__ == "__main__":
    main()
